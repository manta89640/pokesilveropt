#!/usr/bin/env python3
"""
List the functions that farcall and callfar reach through FarCallTargets.

Usage: tools/farcall_targets.py pokegold.sym pokesilver.sym > data/farcall_targets.asm

A farcall is 6 bytes. To a function in data/farcall_targets.asm, it is
"rst FarCallIndexed" and the function's index, 2 bytes, and its entry in
FarCallTargets (in ROM0) is 3 bytes. So this lists the functions that more
than one farcall or callfar reaches, as many as fit in an index. A function
has to be in both builds (the .sym files of a previous build).
"""

import collections
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_TARGETS = 256


def main():
	uses = collections.Counter()
	for root, dirs, files in os.walk(ROOT):
		dirs[:] = sorted(d for d in dirs if d not in ('.git', 'tools'))
		for name in sorted(files):
			if name.endswith('.asm'):
				for line in open(os.path.join(root, name), encoding='utf-8'):
					m = re.match(r'\s+(farcall|callfar)\s+([A-Za-z_]\w*)\s*(;|$)', line)
					if m:
						uses[m.group(2)] += 1
	symbols = []
	for path in sys.argv[1:]:
		symbols.append({m.group(1) for m in re.finditer(r'^[0-9a-f]+:[0-9a-f]+ (\S+)$',
			open(path).read(), re.M)})
	targets = [name for name, count in uses.items()
		if count > 1 and all(name in s for s in symbols)]
	targets = sorted(targets, key=lambda name: -uses[name])[:MAX_TARGETS]
	print('; Functions that farcall and callfar reach through FarCallTargets')
	print('; (generated by tools/farcall_targets.py)')
	print()
	for name in sorted(targets):
		print(f'\tfarcall_target {name}')


if __name__ == '__main__':
	main()
